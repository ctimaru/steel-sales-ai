create or replace function public.p2_rfq_attribution_recovery_status(
  p_organization_id uuid,
  p_limit integer default 100
)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
with access_check as (
  select public.is_organization_member(p_organization_id,false) as allowed
),
recovery_summary as (
  select
    count(*)::int as recovered_messages,
    count(distinct conversation_id)::int as recovered_conversations
  from public.commercial_message_identity_recoveries
  where organization_id=p_organization_id
    and (select allowed from access_check)
),
unresolved as (
  select
    r.id as rfq_id,
    r.conversation_id,
    c.subject,
    c.external_thread_id,
    r.contact_id,
    r.company_id,
    count(m.id)::int as identity_message_count,
    count(distinct m.sender_contact_id)
      filter(where m.sender_contact_id is not null)::int as distinct_contact_count,
    count(distinct m.sender_company_id)
      filter(where m.sender_company_id is not null)::int as distinct_company_count,
    array_remove(
      array_agg(distinct nullif(lower(btrim(m.sender_email)),'')),
      null
    ) as sender_emails,
    max(ct.full_name) filter(where ct.id=r.contact_id) as contact_name
  from public.rfqs r
  join public.conversations c
    on c.organization_id=r.organization_id
   and c.id=r.conversation_id
  left join public.messages m
    on m.organization_id=r.organization_id
   and m.conversation_id=r.conversation_id
   and coalesce(m.direction,'inbound')<>'outbound'
  left join public.contacts ct
    on ct.organization_id=r.organization_id
   and ct.id=r.contact_id
  where r.organization_id=p_organization_id
    and r.company_id is null
    and (select allowed from access_check)
  group by
    r.id,r.conversation_id,c.subject,c.external_thread_id,r.contact_id,r.company_id
),
classified as (
  select
    u.*,
    case
      when u.identity_message_count=0 then 'missing_legacy_message'
      when u.distinct_contact_count>1 or u.distinct_company_count>1 then 'blocked_identity_conflict'
      when u.contact_id is not null and u.distinct_company_count=0 then 'pending_company_confirmation'
      when u.contact_id is null then 'pending_contact_resolution'
      else 'unresolved'
    end as recovery_status
  from unresolved u
),
rows as (
  select *
  from classified
  order by
    case recovery_status
      when 'pending_company_confirmation' then 0
      when 'pending_contact_resolution' then 1
      when 'missing_legacy_message' then 2
      else 3
    end,
    subject,
    rfq_id
  limit greatest(1,least(coalesce(p_limit,100),500))
)
select jsonb_build_object(
  'summary',jsonb_build_object(
    'recovered_messages',(select recovered_messages from recovery_summary),
    'recovered_conversations',(select recovered_conversations from recovery_summary),
    'unattributed_rfqs',(select count(*) from classified),
    'missing_legacy_message',(select count(*) from classified where recovery_status='missing_legacy_message'),
    'pending_company_confirmation',(select count(*) from classified where recovery_status='pending_company_confirmation'),
    'pending_contact_resolution',(select count(*) from classified where recovery_status='pending_contact_resolution'),
    'blocked_identity_conflict',(select count(*) from classified where recovery_status='blocked_identity_conflict')
  ),
  'rfqs',coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'rfq_id',rfq_id,
        'conversation_id',conversation_id,
        'subject',subject,
        'external_thread_id',external_thread_id,
        'contact_id',contact_id,
        'contact_name',contact_name,
        'identity_message_count',identity_message_count,
        'sender_emails',to_jsonb(sender_emails),
        'recovery_status',recovery_status
      )
      order by
        case recovery_status
          when 'pending_company_confirmation' then 0
          when 'pending_contact_resolution' then 1
          when 'missing_legacy_message' then 2
          else 3
        end,
        subject,
        rfq_id
    )
    from rows
  ),'[]'::jsonb),
  'policy',jsonb_build_object(
    'exact_header_only',true,
    'email_domain_inference',false,
    'filename_inference',false,
    'subject_inference',false,
    'body_inference',false,
    'company_requires_verified_contact_mapping',true,
    'multi_message_company_requires_consensus',true,
    'materialize_then_finalize',true
  )
);
$$;

revoke all on function public.p2_rfq_attribution_recovery_status(uuid,integer)
  from public,anon;
grant execute on function public.p2_rfq_attribution_recovery_status(uuid,integer)
  to authenticated,service_role;

