create or replace function private.p1_pilot_checkpoint_impl(p_organization_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  v_actor uuid := auth.uid();
  v_run public.pilot_runs%rowtype;
  v_readiness jsonb;
  v_samples integer;
  v_task_types integer;
  v_faster integer;
  v_same integer;
  v_slower integer;
  v_median_steel numeric;
  v_median_previous numeric;
  v_median_improvement numeric;
begin
  if v_actor is null then
    raise exception using errcode='28000', message='authentication required';
  end if;
  if p_organization_id is null or not public.is_organization_member(p_organization_id,true) then
    raise exception using errcode='42501', message='active tenant membership required';
  end if;

  select * into v_run
  from public.pilot_runs
  where organization_id=p_organization_id and status='active'
  order by started_at desc
  limit 1;

  if v_run.id is null then
    return jsonb_build_object('contract','PA2.37-v1','pilot_active',false,'checkpoint_ready',false);
  end if;

  v_readiness := private.p1_pilot_exit_readiness_impl(p_organization_id,v_run.started_at);

  select
    count(*)::int,
    count(distinct task_type)::int,
    count(*) filter(where comparison='faster')::int,
    count(*) filter(where comparison='same')::int,
    count(*) filter(where comparison='slower')::int,
    percentile_cont(0.5) within group(order by steel_sales_seconds),
    percentile_cont(0.5) within group(order by previous_method_seconds)
  into
    v_samples,v_task_types,v_faster,v_same,v_slower,v_median_steel,v_median_previous
  from public.pilot_human_evidence
  where pilot_run_id=v_run.id;

  if coalesce(v_median_previous,0)>0 then
    v_median_improvement := round((1 - (v_median_steel / v_median_previous)) * 100,1);
  end if;

  return jsonb_build_object(
    'contract','PA2.37-v1',
    'pilot_active',true,
    'pilot_run_id',v_run.id,
    'pilot_started_at',v_run.started_at,
    'quantitative_readiness',v_readiness,
    'human_evidence',jsonb_build_object(
      'sample_count',coalesce(v_samples,0),
      'task_type_count',coalesce(v_task_types,0),
      'faster_count',coalesce(v_faster,0),
      'same_count',coalesce(v_same,0),
      'slower_count',coalesce(v_slower,0),
      'median_steel_sales_seconds',v_median_steel,
      'median_previous_method_seconds',v_median_previous,
      'median_improvement_percent',v_median_improvement,
      'minimum_samples_target',3,
      'minimum_task_types_target',2,
      'evidence_sufficient',coalesce(v_samples,0)>=3 and coalesce(v_task_types,0)>=2
    ),
    'checkpoint_ready',
      coalesce((v_readiness->>'pilot_evidence_ready')::boolean,false)
      and coalesce(v_samples,0)>=3
      and coalesce(v_task_types,0)>=2,
    'interpretation_note',
      'Human time estimates are self-reported evidence and must not be treated as precise causal measurements.'
  );
end;
$$;

