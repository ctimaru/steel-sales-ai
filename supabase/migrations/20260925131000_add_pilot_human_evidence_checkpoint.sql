create table if not exists public.pilot_human_evidence (
  id bigint generated by default as identity primary key,
  pilot_run_id uuid not null references public.pilot_runs(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id) on delete cascade,
  task_type text not null check (task_type in ('search','product_lookup','company_lookup','price_lookup','evidence_check','correction','other')),
  steel_sales_seconds integer not null check (steel_sales_seconds between 1 and 7200),
  previous_method_seconds integer not null check (previous_method_seconds between 1 and 14400),
  comparison text not null check (comparison in ('faster','same','slower')),
  confidence text not null default 'medium' check (confidence in ('low','medium','high')),
  created_at timestamptz not null default now()
);

create index if not exists pilot_human_evidence_run_time_idx
  on public.pilot_human_evidence(pilot_run_id, created_at desc);
create index if not exists pilot_human_evidence_org_time_idx
  on public.pilot_human_evidence(organization_id, created_at desc);

alter table public.pilot_human_evidence enable row level security;
revoke all on table public.pilot_human_evidence from public,anon,authenticated;
grant select,insert,update,delete on table public.pilot_human_evidence to service_role,postgres;
grant usage,select on sequence public.pilot_human_evidence_id_seq to service_role,postgres;

create or replace function private.p1_record_pilot_human_evidence_impl(
  p_organization_id uuid,
  p_task_type text,
  p_steel_sales_seconds integer,
  p_previous_method_seconds integer,
  p_comparison text,
  p_confidence text
)
returns bigint
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_actor uuid := auth.uid();
  v_run_id uuid;
  v_id bigint;
begin
  if v_actor is null then
    raise exception using errcode='28000', message='authentication required';
  end if;
  if p_organization_id is null or not public.is_organization_member(p_organization_id,true) then
    raise exception using errcode='42501', message='active tenant membership required';
  end if;

  select id into v_run_id
  from public.pilot_runs
  where organization_id=p_organization_id and status='active'
  order by started_at desc
  limit 1;

  if v_run_id is null then
    raise exception using errcode='55000', message='active pilot required';
  end if;
  if p_task_type not in ('search','product_lookup','company_lookup','price_lookup','evidence_check','correction','other') then
    raise exception using errcode='22023', message='invalid task type';
  end if;
  if p_comparison not in ('faster','same','slower') then
    raise exception using errcode='22023', message='invalid comparison';
  end if;
  if p_confidence not in ('low','medium','high') then
    raise exception using errcode='22023', message='invalid confidence';
  end if;
  if p_steel_sales_seconds < 1 or p_steel_sales_seconds > 7200
     or p_previous_method_seconds < 1 or p_previous_method_seconds > 14400 then
    raise exception using errcode='22023', message='invalid duration';
  end if;

  insert into public.pilot_human_evidence(
    pilot_run_id,organization_id,actor_user_id,task_type,
    steel_sales_seconds,previous_method_seconds,comparison,confidence
  ) values (
    v_run_id,p_organization_id,v_actor,p_task_type,
    p_steel_sales_seconds,p_previous_method_seconds,p_comparison,p_confidence
  )
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.p1_record_pilot_human_evidence(
  p_organization_id uuid,
  p_task_type text,
  p_steel_sales_seconds integer,
  p_previous_method_seconds integer,
