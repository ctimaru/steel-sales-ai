revoke all on table public.commercial_review_queue from anon, authenticated;
revoke all on sequence public.commercial_observations_id_seq from anon, authenticated;
revoke all on sequence public.commercial_review_queue_id_seq from anon, authenticated;

grant select on table public.commercial_datasets to authenticated;
grant select on table public.commercial_threads to authenticated;
grant select on table public.commercial_observations to authenticated;
grant select on table public.commercial_review_queue to authenticated;
grant update (status, corrected_values, reviewed_at) on table public.commercial_review_queue to authenticated;
