-- Italian VAT (Partita IVA): 11 digits and the Agenzia delle Entrate check digit.
-- Same rule as apps/web/lib/italian-vat.ts.
create or replace function private.selfact1_italian_vat_valid(p_value text)
returns boolean
language plpgsql
immutable
set search_path=''
as $function$
declare
  v_digits text := regexp_replace(upper(coalesce(p_value,'')),'[^A-Z0-9]','','g');
  v_sum integer := 0;
  v_digit integer;
  v_index integer;
begin
  if left(v_digits,2) = 'IT' then
    v_digits := substr(v_digits,3);
  end if;
  if v_digits !~ '^[0-9]{11}$' or v_digits = '00000000000' then
    return false;
  end if;
  for v_index in 1..10 loop
    v_digit := substr(v_digits,v_index,1)::integer;
    if v_index % 2 = 0 then
      v_digit := v_digit * 2;
      if v_digit > 9 then
        v_digit := v_digit - 9;
      end if;
    end if;
    v_sum := v_sum + v_digit;
  end loop;
  return (10 - v_sum % 10) % 10 = substr(v_digits,11,1)::integer;
end;
$function$;

revoke all on function private.selfact1_italian_vat_valid(text) from public, anon, authenticated;

-- Self-service rules. Returns {eligible, reasons[]}; every reason sends the
-- application to staff review instead.
create or replace function private.selfact1_eligibility(p_application_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_app public.company_registration_applications%rowtype;
  v_reasons text[] := array[]::text[];
  v_vat_key text;
  v_identity jsonb;
begin
  select * into v_app
  from public.company_registration_applications
  where id = p_application_id;

  if not found then
    return jsonb_build_object('eligible',false,'reasons',jsonb_build_array('not_found'));
  end if;

  if v_app.application_status <> 'pending_review' then
    v_reasons := v_reasons || 'status_not_pending_review';
  end if;

  if v_app.email_verified_at is null then
    v_reasons := v_reasons || 'email_not_verified';
  end if;

  if v_app.claim_target_network_company_id is not null then
    v_reasons := v_reasons || 'claim_requires_review';
  end if;

  v_vat_key := private.hp4_normalize_identifier(v_app.vat_id);
  if v_app.country_code = 'IT' then
    if not private.selfact1_italian_vat_valid(v_app.vat_id) then
      v_reasons := v_reasons || 'vat_invalid';
    end if;
  elsif v_vat_key is null or char_length(v_vat_key) not between 8 and 18 then
    v_reasons := v_reasons || 'vat_missing';
  end if;

  v_identity := private.selfact1_candidates_core(v_app.id);
  if coalesce((v_identity->>'candidate_count')::integer,0) > 0
     or coalesce((v_identity->>'possible_match_count')::integer,0) > 0 then
    v_reasons := v_reasons || 'identity_candidates';
  end if;

  if v_vat_key is not null and exists (
    select 1
    from public.company_registration_applications other
    where other.id <> v_app.id
      and other.country_code = v_app.country_code
      and private.hp4_normalize_identifier(other.vat_id) in (
        v_vat_key,
        'IT' || v_vat_key,
        case when v_vat_key like 'IT%' then substr(v_vat_key,3) end
      )
      and other.application_status in ('pending_review','needs_information','approved','activated')
  ) then
    v_reasons := v_reasons || 'duplicate_application';
  end if;

  if exists (
    select 1
    from public.organization_memberships m
    where m.user_id = v_app.applicant_user_id
      and m.status = 'active'
  ) then
    v_reasons := v_reasons || 'already_member';
  end if;

  return jsonb_build_object(
    'eligible', cardinality(v_reasons) = 0,
    'reasons', to_jsonb(v_reasons),
    'rules_version', 'selfact1-v1'
  );
end;
$function$;

revoke all on function private.selfact1_eligibility(uuid) from public, anon, authenticated;

create or replace function private.selfact1_self_activate_impl(p_application_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_user uuid := (select auth.uid());
  v_app public.company_registration_applications%rowtype;
  v_eligibility jsonb;
  v_result jsonb;
begin
  if v_user is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select * into v_app
  from public.company_registration_applications
  where id = p_application_id
  for update;

  if not found then
    raise exception 'registration application not found' using errcode = 'P0002';
  end if;

  if v_app.applicant_user_id <> v_user then
    raise exception 'not allowed to activate this registration application' using errcode = '42501';
  end if;

  if v_app.application_status = 'activated' then
    return jsonb_build_object(
      'activated', true,
      'activation_mode', v_app.activation_mode,
      'organization_id', v_app.activated_organization_id,
      'idempotent_replay', true
    );
  end if;

  v_eligibility := private.selfact1_eligibility(p_application_id);
  if not coalesce((v_eligibility->>'eligible')::boolean, false) then
    return jsonb_build_object(
      'activated', false,
      'status', v_app.application_status,
      'reasons', v_eligibility->'reasons'
    );
  end if;

  update public.company_registration_applications
  set
    application_status = 'approved',
    reviewed_at = now(),
    reviewed_by = v_user,
    activation_mode = 'self_service'
  where id = p_application_id;

  perform private.p0a_append_registration_event(
    p_application_id,
    'application_approved',
    v_user,
    'system',
    'pending_review',
    'approved',
    jsonb_build_object('activation_mode','self_service','rules_version',v_eligibility->>'rules_version')
  );

  v_result := private.selfact1_activation_core(
    p_application_id,
    null,
    v_user,
    'system',
    'self_service'
  );

  return v_result || jsonb_build_object('activated', true, 'activation_mode', 'self_service');
end;
$function$;

