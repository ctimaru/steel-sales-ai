-- ONBOARDING-SELF1 · Fase 1 — Self-service activation of eligible registrations.
-- Decision of the founder, 3 Nov 2026 (Notion: ONBOARDING-SELF1).
--
-- * Staff-only activation, network bridge and identity-candidate functions are
--   split into private *_core functions with explicit actor parameters. The
--   existing private impl functions become thin wrappers that still require the
--   same platform permissions, so the staff path is unchanged.
-- * A registration that passes every self-service rule is approved and activated
--   at submission, with activation_mode = 'self_service'. The applicant is the
--   recorded reviewer and the audit events carry actor_type = 'system'.
-- * Anything doubtful (claim of an existing profile, identity candidates, invalid
--   or duplicate VAT, existing membership) stays in pending_review for staff.

alter table public.company_registration_applications
  add column if not exists activation_mode text not null default 'staff_review';

alter table public.company_registration_applications
  add constraint company_registration_applications_activation_mode_check
    check (activation_mode in ('staff_review','self_service'));

comment on column public.company_registration_applications.activation_mode is
  'SELF1: staff_review (decided in the platform console) or self_service (approved and activated automatically at submission because every eligibility rule passed).';

