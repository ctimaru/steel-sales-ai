create or replace function private.selfact1_candidates_core(
  p_application_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_app public.company_registration_applications%rowtype;
  v_app_vat_key text;
  v_app_registration_key text;
  v_app_name_key text;
  v_app_domain text;
  v_candidates jsonb;
  v_possible_matches jsonb;
  v_candidate_count integer;
  v_possible_count integer;
begin

  select *
    into v_app
  from public.company_registration_applications
  where id = p_application_id;

  if not found then
    raise exception 'registration application not found'
      using errcode = 'P0002';
  end if;

  v_app_vat_key := private.hp4_normalize_identifier(v_app.vat_id);
  v_app_registration_key :=
    private.hp4_normalize_identifier(v_app.registration_id);
  v_app_name_key := private.hp4_company_name_key(v_app.legal_name);
  v_app_domain := private.hp4_normalize_domain(v_app.website_url);

  with candidate_base as (
    select
      nc.id as network_company_id,
      nc.legal_name,
      nc.trading_name,
      nc.country_code,
      nc.vat_id,
      nc.registration_id,
      nc.website_domain,
      nc.publication_status,
      nc.claimed_status,
      nc.verification_status,
      (
        nc.country_code = v_app.country_code
        and v_app_vat_key is not null
        and private.hp4_normalize_identifier(nc.vat_id) = v_app_vat_key
      ) as vat_match,
      (
        nc.country_code = v_app.country_code
        and v_app_registration_key is not null
        and private.hp4_normalize_identifier(nc.registration_id) = v_app_registration_key
      ) as registration_match,
      (
        nc.country_code = v_app.country_code
        and v_app_name_key is not null
        and private.hp4_company_name_key(nc.legal_name) = v_app_name_key
      ) as legal_name_match,
      (
        v_app_domain is not null
        and private.hp4_normalize_domain(nc.website_domain) = v_app_domain
      ) as domain_match,
      (
        select l.organization_id
        from public.organization_network_company_links l
        where l.network_company_id = nc.id
          and l.link_status = 'active'
        limit 1
      ) as active_link_organization_id,
      (
        select c.organization_id
        from public.network_company_claims c
        where c.network_company_id = nc.id
          and c.status = 'approved'
        order by c.reviewed_at desc nulls last, c.created_at desc
        limit 1
      ) as approved_claim_organization_id
    from public.network_companies nc
    where nc.publication_status <> 'archived'
  ),
  candidate_enriched as (
    select
      cb.*,
      array_remove(
        array[
          case when cb.vat_match then 'country_vat_exact' end,
          case when cb.registration_match then 'country_registration_exact' end,
          case when cb.legal_name_match then 'country_legal_name_key_exact' end,
          case when cb.domain_match then 'website_domain_exact' end
        ],
        null
      )::text[] as signals,
      (cb.vat_match or cb.registration_match or cb.legal_name_match) as blocking_match,
      case
        when cb.vat_match then 'exact_identifier'
        when cb.registration_match then 'exact_identifier'
        when cb.legal_name_match and cb.domain_match then 'legal_name_and_domain'
        when cb.legal_name_match then 'legal_name_exact'
        else 'shared_domain'
      end as resolution_class,
      case
        when cb.vat_match then 1.0000
        when cb.registration_match then 0.9800
        when cb.legal_name_match and cb.domain_match then 0.9300
        when cb.legal_name_match then 0.8500
        when cb.domain_match then 0.5500
        else 0.0000
      end::numeric(5,4) as match_score
    from candidate_base cb
    where
      cb.vat_match
      or cb.registration_match
      or cb.legal_name_match
      or cb.domain_match
  ),
  candidate_final as (
    select
      ce.*,
      (
        (
          ce.active_link_organization_id is null
          or ce.active_link_organization_id = v_app.activated_organization_id
        )
        and
        (
          ce.approved_claim_organization_id is null
          or ce.approved_claim_organization_id = v_app.activated_organization_id
        )
      ) as selectable
    from candidate_enriched ce
  )
  select
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'network_company_id', cf.network_company_id,
          'legal_name', cf.legal_name,
          'trading_name', cf.trading_name,
          'country_code', cf.country_code,
          'vat_id', cf.vat_id,
          'registration_id', cf.registration_id,
          'website_domain', cf.website_domain,
          'publication_status', cf.publication_status,
          'claimed_status', cf.claimed_status,
          'verification_status', cf.verification_status,
          'signals', cf.signals,
          'resolution_class', cf.resolution_class,
          'match_score', cf.match_score,
          'selectable', cf.selectable,
          'active_link_organization_id', cf.active_link_organization_id,
          'approved_claim_organization_id', cf.approved_claim_organization_id
        )
        order by cf.match_score desc, cf.legal_name, cf.network_company_id
      ) filter (where cf.blocking_match),
      '[]'::jsonb
    ),
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'network_company_id', cf.network_company_id,
          'legal_name', cf.legal_name,
          'trading_name', cf.trading_name,
          'country_code', cf.country_code,
          'vat_id', cf.vat_id,
          'registration_id', cf.registration_id,
          'website_domain', cf.website_domain,
          'publication_status', cf.publication_status,
          'claimed_status', cf.claimed_status,
          'verification_status', cf.verification_status,
          'signals', cf.signals,
          'resolution_class', cf.resolution_class,
          'match_score', cf.match_score,
          'selectable', cf.selectable,
          'active_link_organization_id', cf.active_link_organization_id,
          'approved_claim_organization_id', cf.approved_claim_organization_id
        )
        order by cf.match_score desc, cf.legal_name, cf.network_company_id
      ) filter (
        where not cf.blocking_match
          and cf.domain_match
      ),
      '[]'::jsonb
    )
  into v_candidates, v_possible_matches
  from candidate_final cf;

  v_candidate_count :=
    jsonb_array_length(coalesce(v_candidates, '[]'::jsonb));
  v_possible_count :=
    jsonb_array_length(coalesce(v_possible_matches, '[]'::jsonb));

  return jsonb_build_object(
    'application_id', v_app.id,
    'create_new_allowed', v_candidate_count = 0,
    'candidate_count', v_candidate_count,
    'possible_match_count', v_possible_count,
    'candidates', coalesce(v_candidates, '[]'::jsonb),
    'possible_matches', coalesce(v_possible_matches, '[]'::jsonb)
  );
end;
$function$;

create or replace function private.selfact1_bridge_core(
  p_application_id uuid,
  p_network_company_id uuid,
  p_actor uuid,
  p_actor_type text,
  p_mode text
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_actor uuid;
  v_app public.company_registration_applications%rowtype;
  v_org uuid;
  v_company uuid;
  v_claim uuid;
  v_link uuid;
  v_domain text;
  v_candidates jsonb;
  v_candidate_count integer;
  v_assertion uuid;
  v_role_key text;
  v_role_assignment uuid;
  v_existing_claim public.network_company_claims%rowtype;
begin
  v_actor := p_actor;

  select * into v_app
  from public.company_registration_applications
  where id=p_application_id
  for update;

  if not found then
    raise exception 'registration application not found' using errcode='P0002';
  end if;

  if v_app.application_status<>'activated' then
    raise exception 'registration bridge requires activated application' using errcode='22023';
  end if;

  v_org := v_app.activated_organization_id;
  if v_org is null then
    raise exception 'activated application has no organization' using errcode='23514';
  end if;

  select l.id,l.network_company_id into v_link,v_company
  from public.organization_network_company_links l
  where l.application_id=v_app.id;

  if found then
    if p_network_company_id is not null and p_network_company_id<>v_company then
      raise exception 'application already bridged to another network company' using errcode='23505';
    end if;

    select id into v_claim
    from public.network_company_claims
    where network_company_id=v_company
      and organization_id=v_org
      and status='approved'
    order by reviewed_at desc
    limit 1;

    return jsonb_build_object(
      'application_id',v_app.id,'organization_id',v_org,'network_company_id',v_company,
      'link_id',v_link,'claim_id',v_claim,'created_network_company',false,
      'verification_status',(select verification_status from public.network_companies where id=v_company),
      'idempotent_replay',true
    );
  end if;

  if v_app.matched_network_company_id is not null then
    if p_network_company_id is not null and p_network_company_id<>v_app.matched_network_company_id then
      raise exception 'application matched_network_company_id conflicts with requested target' using errcode='23514';
    end if;
    v_company := v_app.matched_network_company_id;
  else
    v_company := p_network_company_id;
  end if;

  v_domain := null;
  if v_app.website_url is not null then
    v_domain := lower(regexp_replace(
      regexp_replace(btrim(v_app.website_url),'^https?://','','i'),
      '^www\.','','i'
    ));
    v_domain := split_part(v_domain,'/',1);
    v_domain := nullif(v_domain,'');
  end if;

  if v_company is null then
    v_candidates := private.selfact1_candidates_core(v_app.id)->'candidates';
    v_candidate_count := jsonb_array_length(v_candidates);

    if v_candidate_count>0 then
      raise exception 'identity candidates exist; explicit network company selection required' using errcode='22023';
    end if;

    insert into public.network_companies(
      legal_name,trading_name,country_code,vat_id,registration_id,
      website_url,website_domain,description,
      publication_status,claimed_status,verification_status
    )
    values(
      btrim(v_app.legal_name),nullif(btrim(v_app.trading_name),''),
      v_app.country_code,nullif(btrim(v_app.vat_id),''),
      nullif(btrim(v_app.registration_id),''),
      nullif(btrim(v_app.website_url),''),v_domain,
      nullif(btrim(v_app.short_description),''),
      'pending_review','unclaimed','unverified'
    )
    returning id into v_company;

    insert into public.network_data_assertions(
      entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
      ownership_type,asserted_by,confidence,review_state
    )
    values
      ('company',v_company,'legal_name',to_jsonb(btrim(v_app.legal_name)),
       'registration_application','registration_application:'||v_app.id::text,
       'company_managed',v_app.applicant_user_id,1.0000,'accepted'),
      ('company',v_company,'country_code',to_jsonb(v_app.country_code),
       'registration_application','registration_application:'||v_app.id::text,
       'company_managed',v_app.applicant_user_id,1.0000,'accepted');

    if v_app.vat_id is not null then
      insert into public.network_data_assertions(
        entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
        ownership_type,asserted_by,confidence,review_state
      ) values (
        'company',v_company,'vat_id',to_jsonb(v_app.vat_id),'registration_application',
        'registration_application:'||v_app.id::text,'company_managed',
        v_app.applicant_user_id,1.0000,'accepted'
      );
    end if;

    if v_app.registration_id is not null then
      insert into public.network_data_assertions(
        entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
        ownership_type,asserted_by,confidence,review_state
      ) values (
        'company',v_company,'registration_id',to_jsonb(v_app.registration_id),'registration_application',
        'registration_application:'||v_app.id::text,'company_managed',
        v_app.applicant_user_id,1.0000,'accepted'
      );
    end if;

    if v_app.website_url is not null then
      insert into public.network_data_assertions(
        entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
        ownership_type,asserted_by,confidence,review_state
      ) values (
        'company',v_company,'website_url',to_jsonb(v_app.website_url),'registration_application',
        'registration_application:'||v_app.id::text,'company_managed',
        v_app.applicant_user_id,0.9500,'accepted'
      );
    end if;

    foreach v_role_key in array array_prepend(v_app.primary_company_type,v_app.secondary_company_types)
    loop
      v_role_assignment := gen_random_uuid();

      insert into public.network_data_assertions(
        entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
        ownership_type,asserted_by,confidence,review_state
      )
      values(
        'company_role_assignment',v_role_assignment,'role',to_jsonb(v_role_key),
        'registration_application','registration_application:'||v_app.id::text,
        'company_managed',v_app.applicant_user_id,1.0000,'accepted'
      )
      returning id into v_assertion;

      insert into public.network_company_role_assignments(
        id,company_id,role_id,is_primary,source_assertion_id
      )
      select v_role_assignment,v_company,r.id,(v_role_key=v_app.primary_company_type),v_assertion
      from public.network_company_roles r
      where r.canonical_key=v_role_key;
    end loop;
  else
    if not exists(
      select 1 from public.network_companies where id=v_company and publication_status<>'archived'
    ) then
      raise exception 'selected network company not found or archived' using errcode='P0002';
    end if;

    insert into public.network_data_assertions(
      entity_type,entity_id,field_path,asserted_value,source_type,source_reference,
      ownership_type,asserted_by,confidence,review_state
    )
    values
      ('company',v_company,'legal_name',to_jsonb(btrim(v_app.legal_name)),
       'registration_application','registration_application:'||v_app.id::text,
       'company_managed',v_app.applicant_user_id,1.0000,'pending'),
      ('company',v_company,'country_code',to_jsonb(v_app.country_code),
       'registration_application','registration_application:'||v_app.id::text,
       'company_managed',v_app.applicant_user_id,1.0000,'pending');
  end if;

  if exists(
    select 1 from public.organization_network_company_links
    where organization_id=v_org and network_company_id<>v_company and link_status='active'
  ) then
    raise exception 'organization already linked to another network company' using errcode='23505';
  end if;

  select * into v_existing_claim
  from public.network_company_claims
  where network_company_id=v_company and status='approved'
  order by reviewed_at desc
  limit 1;

  if found and v_existing_claim.organization_id<>v_org then
    raise exception 'network company already has an approved claim by another organization' using errcode='23505';
  end if;

  update public.company_registration_applications
  set matched_network_company_id=v_company
  where id=v_app.id;

  insert into public.organization_network_company_links(
    organization_id,network_company_id,application_id,link_status,linked_by
  )
  values(v_org,v_company,v_app.id,'active',v_actor)
  returning id into v_link;

  perform private.p0a_append_registration_event(
    v_app.id,'network_company_linked',v_actor,p_actor_type,'activated','activated',
    jsonb_build_object('organization_id',v_org,'network_company_id',v_company)
  );

  if v_existing_claim.id is not null then
    v_claim := v_existing_claim.id;
  else
    insert into public.network_company_claims(
      network_company_id,organization_id,requested_by,status,
      request_note,reviewed_by,reviewed_at,review_note
    )
    values(
      v_company,v_org,v_app.applicant_user_id,'approved',
      'Created by M7 registration bridge',v_actor,now(),
      'Approved as part of controlled registration bridge'
    )
    returning id into v_claim;

    update public.network_companies
    set claimed_status='claimed'
    where id=v_company;

    perform private.p0a_append_registration_event(
      v_app.id,'claim_created',v_actor,p_actor_type,'activated','activated',
      jsonb_build_object(
        'claim_id',v_claim,'organization_id',v_org,
        'network_company_id',v_company,'claim_status','approved'
      )
    );
  end if;

  if p_mode = 'staff_review' then
    perform private.sa4_record_registration_action(
      'registrations.bridge_network',
      'registration_network_bridge_completed',
      p_application_id,
      'activated',
      'activated',
      case
        when p_network_company_id is null then 'created_or_resolved_network_company'
        else 'linked_existing_network_company'
      end
    );
  end if;

  return jsonb_build_object(
    'application_id',v_app.id,'organization_id',v_org,'network_company_id',v_company,
    'link_id',v_link,'claim_id',v_claim,
    'created_network_company',(p_network_company_id is null and v_app.matched_network_company_id is null),
    'claim_status','approved',
    'verification_status',(select verification_status from public.network_companies where id=v_company),
    'idempotent_replay',false
  );
end;
$function$;

create or replace function private.selfact1_activation_core(
  p_application_id uuid,
  p_network_company_id uuid,
  p_actor uuid,
  p_actor_type text,
  p_mode text
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_actor_user_id uuid;
  v_app public.company_registration_applications%rowtype;
  v_organization_id uuid;
  v_slug_base text;
  v_slug text;
  v_is_default boolean;
  v_existing_membership boolean;
  v_candidates jsonb;
  v_candidate_count integer;
  v_selected_is_candidate boolean;
  v_bridge jsonb;
begin
  v_actor_user_id := p_actor;


  select *
    into v_app
  from public.company_registration_applications
  where id = p_application_id
  for update;

  if not found then
    raise exception 'registration application not found'
      using errcode = 'P0002';
  end if;

  -- Historical activated rows can be healed idempotently through the same
  -- bridge contract without creating another Organization.
  if v_app.application_status = 'activated' then
    if v_app.activated_organization_id is null then
      raise exception 'activated application has no organization'
        using errcode = '23514';
    end if;

    v_bridge := private.selfact1_bridge_core(
      p_application_id,
      p_network_company_id,
      p_actor,
      p_actor_type,
      p_mode
    );

    return jsonb_build_object(
      'application_id', v_app.id,
      'status', v_app.application_status,
      'organization_id', v_app.activated_organization_id,
      'network_company_id', v_bridge->>'network_company_id',
      'claim_id', v_bridge->>'claim_id',
      'bridge_idempotent_replay',
        coalesce((v_bridge->>'idempotent_replay')::boolean, false),
      'idempotent_replay', true
    );
  end if;

  if v_app.application_status <> 'approved' then
    raise exception 'application can only be activated from approved'
      using errcode = '22023';
  end if;

  if v_app.activated_organization_id is not null then
    raise exception 'approved application already references an organization'
      using errcode = '23514';
  end if;

  -- Resolve Network identity before any tenant state is committed.
  v_candidates := private.selfact1_candidates_core(v_app.id)->'candidates';
  v_candidate_count := jsonb_array_length(coalesce(v_candidates, '[]'::jsonb));

  if v_candidate_count > 0 and p_network_company_id is null then
    raise exception
      'identity candidates exist; explicit network company selection required before activation'
      using errcode = '22023';
  end if;

  if p_network_company_id is not null then
    select exists (
      select 1
      from jsonb_array_elements(coalesce(v_candidates, '[]'::jsonb)) candidate
      where candidate->>'network_company_id' = p_network_company_id::text
    )
    into v_selected_is_candidate;

    if not coalesce(v_selected_is_candidate, false) then
      raise exception
        'selected network company is not an identity candidate for this application'
        using errcode = '22023';
    end if;
  end if;

  perform private.p0a_append_registration_event(
    p_application_id,
    'activation_started',
    v_actor_user_id,
    p_actor_type,
    'approved',
    'approved',
    jsonb_build_object(
      'network_candidate_count', v_candidate_count,
      'selected_network_company_id', p_network_company_id
    )
  );

  v_slug_base := regexp_replace(
    lower(btrim(v_app.legal_name)),
    '[^a-z0-9]+',
    '-',
    'g'
  );
  v_slug_base := trim(both '-' from v_slug_base);

  if v_slug_base = '' then
    v_slug_base := 'company';
  end if;

  v_slug :=
    left(v_slug_base, 48) || '-' ||
    left(replace(v_app.id::text, '-', ''), 12);

  insert into public.organizations (
    name,
    slug,
    created_by,
    industry,
    country_code,
    onboarding_status,
    source_preferences,
    onboarding_updated_by
  )
  values (
    btrim(v_app.legal_name),
    v_slug,
    v_app.applicant_user_id,
    'steel',
    v_app.country_code,
    'not_started',
    '{}'::text[],
    v_app.applicant_user_id
  )
  returning id into v_organization_id;

  perform private.p0a_append_registration_event(
    p_application_id,
    'organization_created',
    v_actor_user_id,
    p_actor_type,
    'approved',
    'approved',
    jsonb_build_object(
      'organization_id', v_organization_id,
      'slug', v_slug
    )
  );

  select exists (
    select 1
    from public.organization_memberships om
    where om.user_id = v_app.applicant_user_id
      and om.status = 'active'
      and om.is_default
  )
  into v_existing_membership;

  v_is_default := not v_existing_membership;

  insert into public.organization_memberships (
    organization_id,
    user_id,
    role,
    status,
    is_default,
    business_role
  )
  values (
    v_organization_id,
    v_app.applicant_user_id,
    'admin',
    'active',
    v_is_default,
    null
  )
  on conflict (organization_id, user_id) do update
  set
    role = 'admin',
    status = 'active',
    updated_at = now();

  update public.company_registration_applications
  set
    application_status = 'activated',
    activated_organization_id = v_organization_id,
    reviewed_at = coalesce(reviewed_at, now()),
    reviewed_by = coalesce(reviewed_by, v_actor_user_id)
  where id = p_application_id
  returning * into v_app;

  -- This call runs in the same transaction. Any identity/claim failure rolls
  -- back the Organization, membership and application status update above.
  v_bridge := private.selfact1_bridge_core(
    p_application_id,
    p_network_company_id,
    p_actor,
    p_actor_type,
    p_mode
  );

  perform private.p0a_append_registration_event(
    p_application_id,
    'activation_completed',
    v_actor_user_id,
    p_actor_type,
    'approved',
    'activated',
    jsonb_build_object(
      'organization_id', v_organization_id,
      'membership_role', 'admin',
      'membership_status', 'active',
      'is_default', v_is_default,
      'network_link_status', 'active',
      'network_company_id', v_bridge->>'network_company_id',
      'claim_id', v_bridge->>'claim_id'
    )
  );

  if p_mode = 'staff_review' then
    perform private.sa4_record_registration_action(
      'registrations.activate',
      'registration_workspace_activated',
      p_application_id,
      'approved',
      'activated',
      null
    );
  end if;

  return jsonb_build_object(
    'application_id', v_app.id,
    'status', v_app.application_status,
    'organization_id', v_organization_id,
    'membership_role', 'admin',
    'membership_status', 'active',
    'is_default', v_is_default,
    'network_link_status', 'active',
    'network_company_id', v_bridge->>'network_company_id',
    'claim_id', v_bridge->>'claim_id',
    'created_network_company',
      coalesce((v_bridge->>'created_network_company')::boolean, false),
    'idempotent_replay', false
  );
end;
$function$;

