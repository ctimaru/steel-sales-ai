-- P2.6 — Cross-Thread Relationship Evidence & Conversion Activation.
-- Candidate generation is deterministic and evidence-first. No candidate auto-activates.

create table if not exists public.commercial_relationship_evidence_decisions (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete restrict,
  relationship_type text not null check (relationship_type in ('offer_rfq','order_offer','order_rfq')),
  source_entity_id uuid not null,
  target_entity_id uuid not null,
  source_conversation_id uuid not null references public.conversations(id) on delete restrict,
  target_conversation_id uuid not null references public.conversations(id) on delete restrict,
  company_id uuid not null references public.companies(id) on delete restrict,
  decision text not null check (decision in ('accepted','rejected')),
  evidence_class text not null check (evidence_class in ('strong_review','review')),
  evidence_snapshot jsonb not null,
  note text,
  decided_by uuid not null references auth.users(id) on delete restrict,
  decided_at timestamptz not null default now(),
  unique (organization_id,relationship_type,source_entity_id,target_entity_id)
);

alter table public.commercial_relationship_evidence_decisions enable row level security;

drop policy if exists commercial_relationship_evidence_decisions_select
  on public.commercial_relationship_evidence_decisions;

create policy commercial_relationship_evidence_decisions_select
on public.commercial_relationship_evidence_decisions
for select
to authenticated
using (public.is_organization_member(organization_id,false));

revoke all on table public.commercial_relationship_evidence_decisions from public,anon,authenticated;
grant select on table public.commercial_relationship_evidence_decisions to authenticated;
grant all on table public.commercial_relationship_evidence_decisions to service_role;

create index if not exists commercial_relationship_evidence_decisions_org_idx
  on public.commercial_relationship_evidence_decisions(organization_id,decided_at desc);

create index if not exists commercial_relationship_evidence_decisions_pair_idx
  on public.commercial_relationship_evidence_decisions(
    organization_id,relationship_type,source_entity_id,target_entity_id
  );

alter table public.commercial_relationship_activations
  drop constraint if exists commercial_relationship_activations_evidence_type_check;

alter table public.commercial_relationship_activations
  add constraint commercial_relationship_activations_evidence_type_check
  check (
    evidence_type in (
      'shared_normalized_conversation_exact_product',
      'human_confirmed_cross_thread_evidence'
    )
  );

create or replace function public.p2_cross_thread_candidate_evidence(
  p_organization_id uuid,
  p_relationship_type text,
  p_source_entity_id uuid,
  p_target_entity_id uuid,
  p_window_days integer default 90
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  result jsonb;
begin
  if (select auth.uid()) is null
     or not public.is_organization_member(p_organization_id,false) then
    raise exception 'organization access denied' using errcode='42501';
  end if;

  if p_relationship_type not in ('offer_rfq','order_offer','order_rfq') then
    return null;
  end if;

  if coalesce(p_window_days,0) < 1 or p_window_days > 180 then
    raise exception 'window_days must be between 1 and 180';
  end if;

  with source_entity as (
    select
      'offer'::text entity_kind,
      o.id entity_id,
      o.company_id,
      o.conversation_id,
      o.rfq_id existing_target_id,
      co.name company_name,
      coalesce(ct.started_at,o.offered_at) evidence_start_at,
      coalesce(ct.last_activity_at,o.offered_at) evidence_end_at
    from public.offers o
    join public.conversations c
      on c.organization_id=o.organization_id and c.id=o.conversation_id
    left join public.companies co
      on co.organization_id=o.organization_id and co.id=o.company_id
    left join lateral (
      select min(t.started_at) started_at,max(t.last_activity_at) last_activity_at
      from public.commercial_threads t
      where t.organization_id=o.organization_id
        and t.source_conversation_id::text=c.external_thread_id
    ) ct on true
    where p_relationship_type='offer_rfq'
      and o.organization_id=p_organization_id
      and o.id=p_source_entity_id

    union all

    select
      'order',
      o.id,
      o.company_id,
      o.conversation_id,
      case
        when p_relationship_type='order_offer' then o.offer_id
        else o.rfq_id
      end,
      co.name,
      coalesce(ct.started_at,o.ordered_at),
      coalesce(ct.last_activity_at,o.ordered_at)
    from public.orders o
    join public.conversations c
      on c.organization_id=o.organization_id and c.id=o.conversation_id
    left join public.companies co
      on co.organization_id=o.organization_id and co.id=o.company_id
    left join lateral (
      select min(t.started_at) started_at,max(t.last_activity_at) last_activity_at
      from public.commercial_threads t
      where t.organization_id=o.organization_id
        and t.source_conversation_id::text=c.external_thread_id
    ) ct on true
    where p_relationship_type in ('order_offer','order_rfq')
      and o.organization_id=p_organization_id
      and o.id=p_source_entity_id
  ),
  target_entity as (
    select
      'rfq'::text entity_kind,
      r.id entity_id,
      r.company_id,
      r.conversation_id,
      co.name company_name,
      coalesce(ct.started_at,r.requested_at) evidence_start_at,
      coalesce(ct.last_activity_at,r.requested_at) evidence_end_at
    from public.rfqs r
    join public.conversations c
      on c.organization_id=r.organization_id and c.id=r.conversation_id
    left join public.companies co
      on co.organization_id=r.organization_id and co.id=r.company_id
    left join lateral (
      select min(t.started_at) started_at,max(t.last_activity_at) last_activity_at
      from public.commercial_threads t
      where t.organization_id=r.organization_id
        and t.source_conversation_id::text=c.external_thread_id
    ) ct on true
    where p_relationship_type in ('offer_rfq','order_rfq')
      and r.organization_id=p_organization_id
      and r.id=p_target_entity_id

    union all

    select
      'offer',
      o.id,
      o.company_id,
      o.conversation_id,
      co.name,
      coalesce(ct.started_at,o.offered_at),
      coalesce(ct.last_activity_at,o.offered_at)
    from public.offers o
    join public.conversations c
      on c.organization_id=o.organization_id and c.id=o.conversation_id
    left join public.companies co
      on co.organization_id=o.organization_id and co.id=o.company_id
    left join lateral (
      select min(t.started_at) started_at,max(t.last_activity_at) last_activity_at
      from public.commercial_threads t
      where t.organization_id=o.organization_id
        and t.source_conversation_id::text=c.external_thread_id
    ) ct on true
    where p_relationship_type='order_offer'
      and o.organization_id=p_organization_id
      and o.id=p_target_entity_id
  ),
  source_contact as (
    select
      case
        when count(distinct m.sender_contact_id)=1
          then (min(m.sender_contact_id::text)
                filter(where m.sender_contact_id is not null))::uuid
        else null
      end contact_id
    from source_entity e
    left join public.messages m
      on m.organization_id=p_organization_id
     and m.conversation_id=e.conversation_id
     and coalesce(m.direction,'inbound')<>'outbound'
  ),
  target_contact as (
    select
      case
        when count(distinct m.sender_contact_id)=1
          then (min(m.sender_contact_id::text)
                filter(where m.sender_contact_id is not null))::uuid
        else null
      end contact_id
    from target_entity e
    left join public.messages m
      on m.organization_id=p_organization_id
     and m.conversation_id=e.conversation_id
     and coalesce(m.direction,'inbound')<>'outbound'
  ),
  source_lines as (
    select
      rl.id line_id,
      rl.canonical_product_key,
      concat_ws('|',
        split_part(rl.canonical_product_key,'|',1),
        split_part(rl.canonical_product_key,'|',2),
        split_part(rl.canonical_product_key,'|',6),
        split_part(rl.canonical_product_key,'|',7)
      ) geometry_key,
      rl.raw_spec_text
    from public.rfq_lines rl
    where (select entity_kind from source_entity)='rfq'
      and rl.organization_id=p_organization_id
      and rl.rfq_id=p_source_entity_id
      and rl.canonical_product_key is not null

    union all

    select
      ol.id,
      ol.canonical_product_key,
      concat_ws('|',
        split_part(ol.canonical_product_key,'|',1),
        split_part(ol.canonical_product_key,'|',2),
        split_part(ol.canonical_product_key,'|',6),
        split_part(ol.canonical_product_key,'|',7)
      ),
      ol.raw_spec_text
    from public.offer_lines ol
    where (select entity_kind from source_entity)='offer'
      and ol.organization_id=p_organization_id
      and ol.offer_id=p_source_entity_id
      and ol.canonical_product_key is not null

    union all

    select
      ol.id,
      ol.canonical_product_key,
      concat_ws('|',
        split_part(ol.canonical_product_key,'|',1),
        split_part(ol.canonical_product_key,'|',2),
        split_part(ol.canonical_product_key,'|',6),
        split_part(ol.canonical_product_key,'|',7)
      ),
      ol.raw_spec_text
    from public.order_lines ol
    where (select entity_kind from source_entity)='order'
      and ol.organization_id=p_organization_id
      and ol.order_id=p_source_entity_id
      and ol.canonical_product_key is not null
  ),
  target_lines as (
    select
      rl.id line_id,
      rl.canonical_product_key,
      concat_ws('|',
        split_part(rl.canonical_product_key,'|',1),
        split_part(rl.canonical_product_key,'|',2),
        split_part(rl.canonical_product_key,'|',6),
        split_part(rl.canonical_product_key,'|',7)
      ) geometry_key,
      rl.raw_spec_text
    from public.rfq_lines rl
    where (select entity_kind from target_entity)='rfq'
      and rl.organization_id=p_organization_id
      and rl.rfq_id=p_target_entity_id
      and rl.canonical_product_key is not null

    union all

    select
      ol.id,
      ol.canonical_product_key,
      concat_ws('|',
        split_part(ol.canonical_product_key,'|',1),
        split_part(ol.canonical_product_key,'|',2),
        split_part(ol.canonical_product_key,'|',6),
        split_part(ol.canonical_product_key,'|',7)
      ),
      ol.raw_spec_text
    from public.offer_lines ol
    where (select entity_kind from target_entity)='offer'
      and ol.organization_id=p_organization_id
      and ol.offer_id=p_target_entity_id
      and ol.canonical_product_key is not null

    union all

    select
      ol.id,
      ol.canonical_product_key,
      concat_ws('|',
        split_part(ol.canonical_product_key,'|',1),
        split_part(ol.canonical_product_key,'|',2),
        split_part(ol.canonical_product_key,'|',6),
        split_part(ol.canonical_product_key,'|',7)
      ),
      ol.raw_spec_text
    from public.order_lines ol
    where (select entity_kind from target_entity)='order'
      and ol.organization_id=p_organization_id
      and ol.order_id=p_target_entity_id
      and ol.canonical_product_key is not null
  ),
  source_exact as (
    select canonical_product_key,count(*)::int n
    from source_lines group by canonical_product_key
  ),
  target_exact as (
    select canonical_product_key,count(*)::int n
    from target_lines group by canonical_product_key
  ),
  source_geometry as (
    select geometry_key,count(*)::int n
    from source_lines group by geometry_key
  ),
  target_geometry as (
    select geometry_key,count(*)::int n
    from target_lines group by geometry_key
  ),
  overlap as (
    select
      coalesce((
        select sum(least(s.n,t.n))::int
        from source_exact s
        join target_exact t using(canonical_product_key)
      ),0) exact_product_overlap_count,
      coalesce((
        select sum(least(s.n,t.n))::int
        from source_geometry s
        join target_geometry t using(geometry_key)
      ),0) geometry_overlap_count
  ),
  line_evidence as (
    select coalesce(jsonb_agg(e.obj order by e.canonical_match desc,e.source_line_id,e.target_line_id),'[]'::jsonb) value
    from (
      select
        s.line_id source_line_id,
        t.line_id target_line_id,
        (s.canonical_product_key=t.canonical_product_key) canonical_match,
        jsonb_build_object(
          'source_line_id',s.line_id,
          'target_line_id',t.line_id,
          'source_canonical_product_key',s.canonical_product_key,
          'target_canonical_product_key',t.canonical_product_key,
          'geometry_key',s.geometry_key,
          'canonical_match',s.canonical_product_key=t.canonical_product_key,
          'source_text',s.raw_spec_text,
          'target_text',t.raw_spec_text
        ) obj
      from source_lines s
      join target_lines t using(geometry_key)
      order by (s.canonical_product_key=t.canonical_product_key) desc,s.line_id,t.line_id
      limit 20
    ) e
  ),
  candidate as (
    select
      s.entity_kind source_kind,
      t.entity_kind target_kind,
      s.entity_id source_entity_id,
      t.entity_id target_entity_id,
      s.company_id,
      coalesce(s.company_name,t.company_name) company_name,
      s.conversation_id source_conversation_id,
      t.conversation_id target_conversation_id,
      s.evidence_start_at source_evidence_at,
      t.evidence_end_at target_evidence_at,
      extract(epoch from (s.evidence_start_at-t.evidence_end_at))/3600.0 gap_hours,
      sc.contact_id source_contact_id,
      tc.contact_id target_contact_id,
      sc.contact_id is not null
        and tc.contact_id is not null
        and sc.contact_id=tc.contact_id shared_contact,
      o.exact_product_overlap_count,
      o.geometry_overlap_count,
      le.value line_evidence
    from source_entity s
    cross join target_entity t
    cross join source_contact sc
    cross join target_contact tc
    cross join overlap o
    cross join line_evidence le
    where s.existing_target_id is null
      and s.conversation_id is not null
      and t.conversation_id is not null
      and s.conversation_id<>t.conversation_id
      and s.company_id is not null
      and s.company_id=t.company_id
      and exists (
        select 1
        from public.commercial_company_identity_verifications v
        where v.organization_id=p_organization_id
          and v.company_id=s.company_id
      )
      and s.evidence_start_at is not null
      and t.evidence_end_at is not null
      and s.evidence_start_at>=t.evidence_end_at
      and s.evidence_start_at<=t.evidence_end_at+make_interval(days=>p_window_days)
      and (o.exact_product_overlap_count>0 or o.geometry_overlap_count>0)
  )
  select jsonb_build_object(
    'relationship_type',p_relationship_type,
    'source_kind',source_kind,
    'target_kind',target_kind,
    'source_entity_id',source_entity_id,
    'target_entity_id',target_entity_id,
    'company_id',company_id,
    'company_name',company_name,
    'source_conversation_id',source_conversation_id,
    'target_conversation_id',target_conversation_id,
    'source_evidence_at',source_evidence_at,
    'target_evidence_at',target_evidence_at,
    'gap_hours',round(gap_hours::numeric,2),
    'gap_days',round((gap_hours/24.0)::numeric,2),
    'source_contact_id',source_contact_id,
    'target_contact_id',target_contact_id,
    'shared_contact',shared_contact,
    'exact_product_overlap_count',exact_product_overlap_count,
    'geometry_overlap_count',geometry_overlap_count,
    'evidence_class',case
      when shared_contact and gap_hours<=720 and geometry_overlap_count>0
        then 'strong_review'
      else 'review'
    end,
    'reason_codes',to_jsonb(array_remove(array[
      'same_verified_company',
      'distinct_conversation',
      'chronological_window',
      case when shared_contact then 'same_exact_contact' end,
      case when exact_product_overlap_count>0 then 'exact_canonical_product_overlap' end,
      case when geometry_overlap_count>0 then 'exact_geometry_overlap' end
    ],null)),
    'line_evidence',line_evidence
  )
  into result
  from candidate;

  return result;
end;
$$;

revoke all on function public.p2_cross_thread_candidate_evidence(uuid,text,uuid,uuid,integer)
