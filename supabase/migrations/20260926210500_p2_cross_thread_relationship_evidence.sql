grant execute on function public.p2_cross_thread_candidate_evidence(uuid,text,uuid,uuid,integer)
  to authenticated,service_role;

create or replace function public.p2_cross_thread_relationship_evidence(
  p_organization_id uuid,
  p_window_days integer default 90,
  p_limit integer default 100,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  result jsonb;
begin
  if (select auth.uid()) is null
     or not public.is_organization_member(p_organization_id,false) then
    raise exception 'organization access denied' using errcode='42501';
  end if;

  if coalesce(p_window_days,0) < 1 or p_window_days > 180 then
    raise exception 'window_days must be between 1 and 180';
  end if;

  with verified_companies as (
    select distinct company_id
    from public.commercial_company_identity_verifications
    where organization_id=p_organization_id
  ),
  raw_pairs as (
    select
      'offer_rfq'::text relationship_type,
      o.id source_entity_id,
      r.id target_entity_id
    from public.offers o
    join public.rfqs r
      on r.organization_id=o.organization_id
     and r.company_id=o.company_id
     and r.conversation_id is distinct from o.conversation_id
    where o.organization_id=p_organization_id
      and o.rfq_id is null
      and o.company_id in (select company_id from verified_companies)

    union all

    select
      'order_offer',
      o.id,
      f.id
    from public.orders o
    join public.offers f
      on f.organization_id=o.organization_id
     and f.company_id=o.company_id
     and f.conversation_id is distinct from o.conversation_id
    where o.organization_id=p_organization_id
      and o.offer_id is null
      and o.company_id in (select company_id from verified_companies)

    union all

    select
      'order_rfq',
      o.id,
      r.id
    from public.orders o
    join public.rfqs r
      on r.organization_id=o.organization_id
     and r.company_id=o.company_id
     and r.conversation_id is distinct from o.conversation_id
    where o.organization_id=p_organization_id
      and o.rfq_id is null
      and o.company_id in (select company_id from verified_companies)
  ),
  undecided_pairs as (
    select p.*
    from raw_pairs p
    where not exists (
      select 1
      from public.commercial_relationship_evidence_decisions d
      where d.organization_id=p_organization_id
        and d.relationship_type=p.relationship_type
        and d.source_entity_id=p.source_entity_id
        and d.target_entity_id=p.target_entity_id
    )
      and not exists (
        select 1
        from public.commercial_relationship_activations a
        where a.organization_id=p_organization_id
          and a.relationship_type=p.relationship_type
          and a.source_entity_id=p.source_entity_id
          and a.target_entity_id=p.target_entity_id
          and a.status='applied'
      )
  ),
  evidence as (
    select e.payload
    from undecided_pairs p
    cross join lateral (
      select public.p2_cross_thread_candidate_evidence(
        p_organization_id,
        p.relationship_type,
        p.source_entity_id,
        p.target_entity_id,
        p_window_days
      ) payload
    ) e
    where e.payload is not null
  ),
  ordered as (
    select payload
    from evidence
    order by
      case payload->>'evidence_class'
        when 'strong_review' then 0
        else 1
      end,
      (payload->>'gap_hours')::numeric,
      payload->>'relationship_type',
      payload->>'source_entity_id'
  ),
  paged as (
    select payload
    from ordered
    limit greatest(1,least(coalesce(p_limit,100),500))
    offset greatest(0,coalesce(p_offset,0))
  ),
  decision_summary as (
    select
      count(*) filter(where decision='accepted')::int accepted,
      count(*) filter(where decision='rejected')::int rejected
    from public.commercial_relationship_evidence_decisions
    where organization_id=p_organization_id
  )
  select jsonb_build_object(
    'summary',jsonb_build_object(
      'pending_total',(select count(*) from evidence),
      'strong_review_count',(select count(*) from evidence where payload->>'evidence_class'='strong_review'),
      'review_count',(select count(*) from evidence where payload->>'evidence_class'='review'),
      'offer_rfq_pending',(select count(*) from evidence where payload->>'relationship_type'='offer_rfq'),
      'order_offer_pending',(select count(*) from evidence where payload->>'relationship_type'='order_offer'),
      'order_rfq_pending',(select count(*) from evidence where payload->>'relationship_type'='order_rfq'),
      'accepted_total',(select accepted from decision_summary),
      'rejected_total',(select rejected from decision_summary)
    ),
    'candidates',coalesce(
      (select jsonb_agg(payload) from paged),
      '[]'::jsonb
    ),
    'policy',jsonb_build_object(
      'window_days',p_window_days,
      'verified_same_company_required',true,
      'distinct_conversation_required',true,
      'chronological_order_required',true,
      'canonical_or_exact_geometry_overlap_required',true,
      'strong_review_max_days',30,
      'human_decision_required',true,
      'automatic_activation',false,
      'email_domain_inference',false,
      'filename_inference',false,
      'subject_similarity',false,
      'embedding_similarity',false,
      'fuzzy_dimension_tolerance',false,
      'geometry_only_line_fk',false
    )
  )
  into result;

  return result;
end;
$$;

revoke all on function public.p2_cross_thread_relationship_evidence(uuid,integer,integer,integer)
  from public,anon;
grant execute on function public.p2_cross_thread_relationship_evidence(uuid,integer,integer,integer)
  to authenticated,service_role;

create or replace function private.p2_decide_cross_thread_relationship_impl(
  p_organization_id uuid,
  p_relationship_type text,
  p_source_entity_id uuid,
  p_target_entity_id uuid,
  p_decision text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := (select auth.uid());
  evidence jsonb;
  decision_id bigint;
  activation_id bigint;
  existing_target uuid;
  linked_line_count integer := 0;
  outcome_result jsonb;
begin
  if actor_id is null then
    raise exception 'Authentication required';
  end if;

  if not public.is_organization_member(p_organization_id,true) then
    raise exception 'Active organization write membership required';
  end if;

  if p_relationship_type not in ('offer_rfq','order_offer','order_rfq') then
    raise exception 'Unsupported relationship type';
  end if;

  if p_decision not in ('accepted','rejected') then
    raise exception 'Decision must be accepted or rejected';
  end if;

  if exists (
    select 1
    from public.commercial_relationship_evidence_decisions d
    where d.organization_id=p_organization_id
      and d.relationship_type=p_relationship_type
      and d.source_entity_id=p_source_entity_id
      and d.target_entity_id=p_target_entity_id
  ) then
    return jsonb_build_object('status','already_decided');
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    'p2.6:'||p_organization_id::text||':'||p_relationship_type||':'||p_source_entity_id::text,0
  ));

  if p_relationship_type='offer_rfq' then
    select rfq_id
    into existing_target
    from public.offers
    where organization_id=p_organization_id and id=p_source_entity_id
    for update;
  elsif p_relationship_type='order_offer' then
    select offer_id
    into existing_target
    from public.orders
    where organization_id=p_organization_id and id=p_source_entity_id
    for update;
  else
    select rfq_id
    into existing_target
    from public.orders
    where organization_id=p_organization_id and id=p_source_entity_id
    for update;
  end if;

  if existing_target is not null then
    return jsonb_build_object(
      'status','blocked',
      'reason','conflicting_or_existing_relationship',
      'existing_target_id',existing_target
    );
  end if;

  evidence := public.p2_cross_thread_candidate_evidence(
    p_organization_id,
    p_relationship_type,
    p_source_entity_id,
    p_target_entity_id,
    90
  );

  if evidence is null then
    return jsonb_build_object(
      'status','blocked',
      'reason','candidate_no_longer_eligible'
    );
  end if;

  insert into public.commercial_relationship_evidence_decisions(
    organization_id,
    relationship_type,
    source_entity_id,
    target_entity_id,
    source_conversation_id,
    target_conversation_id,
    company_id,
    decision,
    evidence_class,
    evidence_snapshot,
    note,
    decided_by
  ) values (
    p_organization_id,
    p_relationship_type,
    p_source_entity_id,
    p_target_entity_id,
    (evidence->>'source_conversation_id')::uuid,
    (evidence->>'target_conversation_id')::uuid,
    (evidence->>'company_id')::uuid,
    p_decision,
    evidence->>'evidence_class',
    evidence,
    nullif(btrim(coalesce(p_note,'')),''),
    actor_id
  )
  returning id into decision_id;

  if p_decision='rejected' then
    return jsonb_build_object(
      'status','rejected',
      'decision_id',decision_id,
      'relationship_type',p_relationship_type,
      'source_entity_id',p_source_entity_id,
      'target_entity_id',p_target_entity_id
    );
  end if;

  if p_relationship_type='offer_rfq' then
    update public.offers
    set rfq_id=p_target_entity_id
    where organization_id=p_organization_id
      and id=p_source_entity_id
      and rfq_id is null;

    update public.offer_lines ol
    set rfq_line_id=(
      select rl.id
      from public.rfq_lines rl
      where rl.organization_id=p_organization_id
        and rl.rfq_id=p_target_entity_id
        and rl.canonical_product_key=ol.canonical_product_key
      limit 1
    )
    where ol.organization_id=p_organization_id
      and ol.offer_id=p_source_entity_id
      and ol.canonical_product_key is not null
      and (
        select count(*)
        from public.rfq_lines rl
        where rl.organization_id=p_organization_id
          and rl.rfq_id=p_target_entity_id
          and rl.canonical_product_key=ol.canonical_product_key
      )=1;
    get diagnostics linked_line_count=row_count;

  elsif p_relationship_type='order_offer' then
    update public.orders
    set offer_id=p_target_entity_id
    where organization_id=p_organization_id
      and id=p_source_entity_id
      and offer_id is null;

    update public.order_lines ol
    set offer_line_id=(
      select fl.id
      from public.offer_lines fl
      where fl.organization_id=p_organization_id
        and fl.offer_id=p_target_entity_id
        and fl.canonical_product_key=ol.canonical_product_key
      limit 1
    )
    where ol.organization_id=p_organization_id
      and ol.order_id=p_source_entity_id
      and ol.canonical_product_key is not null
      and (
        select count(*)
        from public.offer_lines fl
        where fl.organization_id=p_organization_id
          and fl.offer_id=p_target_entity_id
          and fl.canonical_product_key=ol.canonical_product_key
      )=1;
    get diagnostics linked_line_count=row_count;

  else
    update public.orders
    set rfq_id=p_target_entity_id
    where organization_id=p_organization_id
      and id=p_source_entity_id
      and rfq_id is null;
  end if;

  insert into public.commercial_relationship_activations(
    organization_id,
    relationship_type,
    source_entity_id,
    target_entity_id,
    evidence_type,
    status,
    activated_by,
    metadata
  ) values (
    p_organization_id,
    p_relationship_type,
    p_source_entity_id,
    p_target_entity_id,
    'human_confirmed_cross_thread_evidence',
    'applied',
    actor_id,
    jsonb_build_object(
      'phase','P2.6',
      'decision_id',decision_id,
      'evidence_class',evidence->>'evidence_class',
      'gap_hours',evidence->'gap_hours',
      'shared_contact',evidence->'shared_contact',
      'exact_product_overlap_count',evidence->'exact_product_overlap_count',
      'geometry_overlap_count',evidence->'geometry_overlap_count',
      'linked_line_count',linked_line_count,
      'execution_mode','single_human_confirmed_cross_thread'
    )
  )
  returning id into activation_id;

  outcome_result := private.p2_reconcile_commercial_outcome_attribution_impl(
    p_organization_id
  );

  return jsonb_build_object(
    'status','applied',
    'decision_id',decision_id,
    'activation_id',activation_id,
    'relationship_type',p_relationship_type,
    'source_entity_id',p_source_entity_id,
    'target_entity_id',p_target_entity_id,
    'linked_line_count',linked_line_count,
    'evidence_class',evidence->>'evidence_class',
    'outcome_reconciliation',outcome_result
  );
end;
$$;

