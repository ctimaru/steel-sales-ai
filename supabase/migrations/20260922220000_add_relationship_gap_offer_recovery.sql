  p_organization_id uuid,
  p_thread_id uuid
)
returns jsonb
language sql
security invoker
set search_path=''
as $$
  select private.recover_shadow_duplicate_offer_impl(p_organization_id,p_thread_id);
$$;

revoke all on function public.p1_recover_shadow_duplicate_offer(uuid,uuid) from public,anon;
grant execute on function public.p1_recover_shadow_duplicate_offer(uuid,uuid) to authenticated,service_role;
