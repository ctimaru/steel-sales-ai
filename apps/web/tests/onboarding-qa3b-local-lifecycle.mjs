/**
 * ONBOARDING-QA3.B — isolated GoTrue resend, invite delivery, invalid OTP,
 * and account lifecycle across independent authenticated sessions.
 * Never connect to hosted Supabase or SMTP; never log credentials, tokens,
 * message bodies, or auth links.
 */
import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { createClient } from "@supabase/supabase-js";

const AUTH = "http://127.0.0.1:54321";
const SITE = "http://127.0.0.1:3000";
const MAILPIT = "http://127.0.0.1:54324";
assert.equal(process.env.NEXT_PUBLIC_SUPABASE_URL, AUTH);
assert.equal(process.env.NEXT_PUBLIC_SITE_URL, SITE);
assert.equal(process.env.FLOW1_LOCAL_PROVIDER, "true");
assert.ok(process.env.RUNNER_TEMP, "Disposable CI is mandatory");

const anonKey = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
const serviceKey = process.env.DEMOTEST23_LOCAL_SERVICE_ROLE_KEY;
assert.ok(anonKey?.length > 20 && serviceKey?.length > 20,
  "Only disposable Supabase keys passed from FLOW1 are permitted");
const noPersist = { auth: { autoRefreshToken: false, persistSession: false } };
const admin = createClient(AUTH, serviceKey, noPersist);
function client() { return createClient(AUTH, anonKey, noPersist); }
const suffix = randomBytes(9).toString("hex");
const strongPassword = randomBytes(24).toString("base64url") + "Aa!1";
let checks = 0;
function pass(name) { checks++; console.log("ONBOARDING-QA3.B LOCAL PASS", name); }
function fakeEmail(label) { return `qa3b-${label}-${suffix}@example.test`; }

async function mailMessages() {
  const resp = await fetch(MAILPIT + "/api/v1/messages", { signal: AbortSignal.timeout(7000) });
  assert.equal(resp.status, 200, "Local Mailpit must be available");
  const list = await resp.json();
  assert.ok(Array.isArray(list.messages));
  return list.messages;
}
function toRecipient(item, address) {
  return (item.To ?? []).some(to => String(to.Address ?? "").toLowerCase() === address);
}
async function received(address, subject) {
  for (let i = 0; i < 25; i++) {
    const found = (await mailMessages()).find(m =>
      toRecipient(m, address) && String(m.Subject ?? "").includes(subject));
    if (found) {
      const resp = await fetch(MAILPIT + "/api/v1/message/" + encodeURIComponent(found.ID));
      assert.equal(resp.status, 200);
      const body = await resp.json();
      assert.ok(typeof body.HTML === "string" && body.HTML.includes("Smart Steel Sales"));
      return body.HTML;
    }
    await new Promise(resolve => setTimeout(resolve, 350));
  }
  throw new Error("Expected branded local email not captured");
}

try {
  await mailMessages();
  pass("local Mailpit only");

  // GoTrue signup should not create a logged-in session until mail confirmation.
  const signupEmail = fakeEmail("resend");
  const signup = client();
  const returnPath = "/en/register?return_to=%2Fen%2Fdistinta";
  const callback = SITE + "/auth/finish?signup=1&next=" + encodeURIComponent(returnPath);
  const first = await signup.auth.signUp({
    email: signupEmail,
    password: strongPassword,
    options: { emailRedirectTo: callback },
  });
  assert.ifError(first.error);
  assert.ok(first.data.user?.id);
  assert.equal(first.data.session, null);
  pass("new signup remains pending verification");

  const message = await received(signupEmail, "Conferma");
  assert.ok(message.includes("token_hash=") && message.includes("redirect_to="));
  pass("branded confirmation message generated by local GoTrue");

  const attempt = await signup.auth.resend({
    type: "signup", email: signupEmail,
    options: { emailRedirectTo: callback },
  });
  if (attempt.error) {
    // GoTrue's first-email cooldown differs between local/provider versions.
    assert.ok(attempt.error.status === 429 ||
      ["over_email_send_rate_limit", "over_request_rate_limit"].includes(attempt.error.code),
      "Resend rejected for an unexpected reason");
    pass("immediate resend is safely rate-limited");
  } else {
    assert.ok(attempt.data.user || attempt.data.messageId || !attempt.error);
    pass("resend accepted without premature authentication");
  }

  // Invalid verification must fail closed, stay on our own domain, and avoid
  // reflecting a token or arbitrary commercial destination.
  const bad = await fetch(SITE + "/auth/confirm?token_hash=invalidQA3Bnonce&type=email&next=" +
    encodeURIComponent("https://attacker.invalid/path"), { redirect: "manual" });
  assert.ok([302,303,307,308].includes(bad.status));
  const failedLocation = new URL(bad.headers.get("location") ?? "", SITE);
  assert.equal(failedLocation.origin, SITE);
  assert.equal(failedLocation.pathname, "/verify-email");
  assert.ok(failedLocation.searchParams.has("error"));
  assert.ok(!failedLocation.href.includes("invalidQA3Bnonce"));
  pass("invalid verification hash rejected without open redirect");

  // This exercises Auth's actual invitation message pipeline, not HP8
  // organization membership issuance. Those require separate worker/RPC QA.
  const inviteEmail = fakeEmail("invite");
  const invitationId = "00000000-0000-4000-8000-" + randomBytes(6).toString("hex");
  const invited = await admin.auth.admin.inviteUserByEmail(inviteEmail, {
    redirectTo: SITE + "/auth/finish?invited=1&invitation_id=" + invitationId,
  });
  assert.ifError(invited.error);
  assert.ok(invited.data.user?.id);
  pass("GoTrue invite issued for a synthetic, isolated identity");

  const inviteHtml = await received(inviteEmail, "invitato");
  assert.ok(inviteHtml.includes("Accetta l’invito"));
  const href = [...inviteHtml.matchAll(/href=["']([^"']+)["']/gi)]
    .map(m => m[1].replaceAll("&amp;", "&"))
    .find(url => url.includes("/auth/v1/verify") && url.includes("type=invite"));
  assert.ok(href, "Invite must use Supabase's signed confirmation URL");
  const inviteURL = new URL(href);
  assert.equal(inviteURL.origin, AUTH);
  const redirectParam = inviteURL.searchParams.get("redirect_to");
  assert.ok(redirectParam && redirectParam.startsWith(SITE + "/auth/finish?"),
    "Invite must return to our canonical account finish flow");
  assert.equal(new URL(redirectParam).searchParams.get("invitation_id"), invitationId);
  pass("branded invite contains an isolated GoTrue token and bounded account callback");

  // A GoTrue invite alone is not an HP8 invitation. No private company
  // membership can be synthesized by calling the Auth invite endpoint.
  const unapproved = client();
  const premature = await unapproved.auth.signInWithPassword({
    email: inviteEmail, password: strongPassword,
  });
  assert.ok(premature.error || !premature.data.session);
  pass("invite alone does not produce a company login");

  // Two independent GoTrue sessions of the same synthetic confirmed account.
  // Test suspension at the database lifecycle layer, not JWT invalidation;
  // access JWTs can outlive refresh revocation until their short expiry.
  const lifecycleEmail = fakeEmail("sessions");
  const created = await admin.auth.admin.createUser({
    email: lifecycleEmail, password: strongPassword, email_confirm: true,
  });
  assert.ifError(created.error);
  assert.ok(created.data.user?.id);
  const firstSession = client();
  const secondSession = client();
  for (const session of [firstSession, secondSession]) {
    const login = await session.auth.signInWithPassword({
      email: lifecycleEmail, password: strongPassword,
    });
    assert.ifError(login.error);
    assert.ok(login.data.session?.access_token);
  }
  pass("two independent real GoTrue sessions established");

  for (const session of [firstSession, secondSession]) {
    const status = await session.rpc("lr5_account_lifecycle_state");
    assert.ifError(status.error);
    assert.equal(status.data?.access_suspended, false);
  }
  pass("both sessions initially unsuspended");

  const deniedClosure = await firstSession.rpc("lr5_request_account_erasure", {
    p_confirmation: "NO",
  });
  assert.ok(deniedClosure.error, "Account suspension must require exact confirmation");
  pass("account closure denies missing explicit confirmation");

  const closure = await firstSession.rpc("lr5_request_account_erasure", {
    p_confirmation: "DELETE_MY_ACCOUNT",
  });
  assert.ifError(closure.error);
  assert.equal(closure.data?.access_suspended, true);
  assert.equal(closure.data?.requested, true);
  pass("explicit synthetic account closure suspends access");

  for (const session of [firstSession, secondSession]) {
    const status = await session.rpc("lr5_account_lifecycle_state");
    assert.ifError(status.error);
    assert.equal(status.data?.access_suspended, true);
  }
  pass("suspension visible across both existing authenticated sessions");

  // Login route checks lifecycle after password auth and signs out globally.
  const after = await fetch(SITE + "/login", { redirect: "manual" });
  assert.equal(after.status, 200);
  pass("login surface remains available; lifecycle redirects are app gated");

} finally {
  await admin.auth.signOut().catch(() => {});
}
assert.equal(checks, 14, "Expected fourteen independent QA3.B gates");
console.log("ONBOARDING-QA3.B LOCAL AUTH LIFECYCLE PASS", checks, "readable checks; zero production writes");
